public class Loops{
    public static void main(String[] args){
        //While Loop
        int i =1;
        while(i<=5){
            System.out.println(i);
            i++;
        }
        //do-while Loop
        int b = 10;
        do{
            System.out.println(b);
            b++;
        }while(b<5);

        //For Loop
        for(int j=0;j<10;j++){
            System.out.println(2*j+1);
        }

        for(int n=5;n>0;n--){
            System.out.println(n);
        }
    }
}